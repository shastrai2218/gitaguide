"""HTTP adapter for the closed-beta chat UI (``/api/*``).

This module is a **translation layer and nothing else**. It calls the same
:meth:`GuidanceOrchestrator.handle_turn` the existing ``POST /chat`` route
calls, and reshapes the result into the flat contract the beta frontend
consumes. It contains no pipeline logic: no safety decision, no retrieval, no
generation, no memory policy.

Why a second surface rather than a change to ``/chat``: the rich trace on
``/chat`` is a research artefact used by the evaluation scripts and the
explanation panel, and its shape must stay free to change. The beta UI needs a
small, stable envelope. Keeping them separate means the UI cannot pin the
research format in place.

Contract::

    POST /api/chat {session_id, message}
      -> {reply, blocked,
          emotion {label, score},
          intent  {label, crisis_score},
          message_id,
          citations [{source, ref, text}],
          memory  {turn_count, summary_included, recent_turns_injected},
          meta    {provider, model, latency_ms, stage_latency_ms}}

    POST /api/consent {session_id, version}
      -> {session_id, consent_version, consent_at}

    POST /api/feedback {message_id, rating, comment}
      -> {message_id, rating, comment}

    GET /api/sessions/{session_id}/messages
      -> {session_id, messages: [{id, role, content, blocked, created_at}]}

Consent is enforced here, on the server. A browser flag is a UI convenience;
it is not a record, and it is not evidence. ``/api/chat`` returns **409** for a
session with no stored consent at the current version, so a tester who clears
storage, opens a second browser, or calls the API directly is asked again
rather than quietly served.
"""

from __future__ import annotations

import logging
from datetime import UTC, datetime
from typing import Annotated, Literal

from fastapi import APIRouter, HTTPException, Query, Request, status
from pydantic import BaseModel, Field

from app.api.ratelimit import RATE_LIMITED_MESSAGE, RateLimiter, client_ip_from
from app.api.routes import OrchestratorDep
from app.db.repository import FeedbackRecord
from app.pipeline.orchestrator import GuidanceOrchestrator
from app.pipeline.schemas import GuidanceResult, UserTurn
from app.telemetry import Telemetry

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api", tags=["beta-ui"])


# --------------------------------------------------------------------------- #
# Wire models
# --------------------------------------------------------------------------- #
class BetaChatRequest(BaseModel):
    """``POST /api/chat`` body. The session id is generated by the browser."""

    message: str = Field(min_length=1, max_length=4000)
    session_id: str | None = Field(default=None, max_length=64)


class BetaEmotion(BaseModel):
    label: str = "neutral"
    score: float = 0.0


class BetaIntent(BaseModel):
    label: str = "other"
    crisis_score: float = 0.0


class BetaCitation(BaseModel):
    """One cited verse, flattened to what the UI renders in a verse leaf."""

    source: str
    ref: str
    text: str


class BetaMemory(BaseModel):
    """What the memory stage put into this turn's prompt.

    Projected straight from :class:`app.pipeline.schemas.MemoryTrace`, which the
    memory stage itself produces. The adapter deliberately does not read the
    repository to recompute any of this: there is exactly one source of memory
    truth and it is the pipeline.
    """

    turn_count: int | None = None
    summary_included: bool | None = None
    recent_turns_injected: int | None = None


class BetaMeta(BaseModel):
    provider: str | None = None
    model: str | None = None
    latency_ms: float | None = None
    #: Wall-clock ms per pipeline stage, keyed by stage name. Empty only if the
    #: pipeline recorded nothing, which would itself be a defect.
    stage_latency_ms: dict[str, float] = Field(default_factory=dict)


class BetaChatResponse(BaseModel):
    #: Needed by the UI to attach feedback to this specific turn.
    message_id: str = ""
    reply: str
    blocked: bool = False
    emotion: BetaEmotion = Field(default_factory=BetaEmotion)
    intent: BetaIntent = Field(default_factory=BetaIntent)
    citations: list[BetaCitation] = Field(default_factory=list)
    memory: BetaMemory = Field(default_factory=BetaMemory)
    meta: BetaMeta = Field(default_factory=BetaMeta)


class BetaMessage(BaseModel):
    id: str
    role: str
    content: str
    blocked: bool = False
    created_at: datetime


class BetaMessagesResponse(BaseModel):
    session_id: str
    messages: list[BetaMessage] = Field(default_factory=list)


class BetaConsentRequest(BaseModel):
    """``POST /api/consent`` body."""

    session_id: str = Field(min_length=1, max_length=64)
    version: str = Field(min_length=1, max_length=32)


class BetaConsentResponse(BaseModel):
    session_id: str
    consent_version: str
    consent_at: datetime


#: Sent with the 409 so the UI can tell "consent needed" apart from a real error.
CONSENT_REQUIRED_CODE = "consent_required"


class BetaFeedbackRequest(BaseModel):
    """``POST /api/feedback`` body.

    The comment is capped short on purpose. It is a reaction to one turn, not a
    bug report, and a long free-text field invites testers to paste the personal
    detail the consent notice asked them not to enter.
    """

    message_id: str = Field(min_length=1, max_length=36)
    rating: Literal["up", "down"]
    comment: str = Field(default="", max_length=500)


class BetaFeedbackResponse(BaseModel):
    message_id: str
    rating: str
    comment: str = ""


# --------------------------------------------------------------------------- #
# Projection
# --------------------------------------------------------------------------- #
def _citations_for(result: GuidanceResult) -> list[BetaCitation]:
    """The verses the answer actually cited, in the order the answer cites them.

    A blocked turn ran no retrieval, so it has nothing to cite. An
    output-blocked turn *did* retrieve, but its answer was replaced by the
    crisis response - attaching verse citations to that text would attribute
    words to scripture that scripture did not say, so those are dropped too.
    """
    if result.crisis or result.output_safety.blocked:
        return []
    if result.retrieval is None or result.generation is None:
        return []

    by_id = {item.verse.id: item.verse for item in result.retrieval.results}
    citations: list[BetaCitation] = []
    for verse_id in result.generation.citations:
        verse = by_id.get(verse_id)
        if verse is None:  # a hallucinated id; already flagged upstream
            continue
        citations.append(
            BetaCitation(
                source=verse.source.value,
                ref=verse.citation,
                text=verse.text_english,
            )
        )
    return citations


# --------------------------------------------------------------------------- #
# Consent
# --------------------------------------------------------------------------- #
async def _require_consent(
    request: Request, orchestrator: GuidanceOrchestrator, session_id: str | None
) -> None:
    """Raise 409 unless this session consented to the current version.

    A session that has never been created has never consented, so the absence of
    a row is a refusal, not a default-yes. Reading the session here costs one
    indexed primary-key lookup, which is cheap next to the two NIM calls it
    guards.
    """
    settings = getattr(request.app.state, "settings", None)
    if settings is not None and not settings.consent_required:
        return

    required = settings.consent_version if settings is not None else "v1"
    record = await orchestrator.repository.get_session(session_id) if session_id else None
    if record is not None and record.consent_version == required:
        return

    logger.info(
        "consent required: session=%s stored=%s required=%s",
        session_id or "-",
        (record.consent_version if record else None) or "none",
        required,
    )
    raise HTTPException(
        status_code=status.HTTP_409_CONFLICT,
        detail={
            "code": CONSENT_REQUIRED_CODE,
            "message": "Please read and accept the beta notice before continuing.",
            "required_version": required,
        },
    )


# --------------------------------------------------------------------------- #
# Rate limiting
# --------------------------------------------------------------------------- #
def _client_ip(request: Request) -> str | None:
    """The address to rate-limit this request on.

    Delegates the proxy reasoning to
    :func:`app.api.ratelimit.client_ip_from`, which reads ``X-Forwarded-For``
    only as far as the configured number of trusted proxies allows. Used solely
    as a rate-limit key; nothing security-relevant is decided from it.
    """
    settings = getattr(request.app.state, "settings", None)
    hops = settings.rate_limit_trusted_proxy_hops if settings is not None else 0
    return client_ip_from(
        request.headers.get("x-forwarded-for"),
        request.client.host if request.client else None,
        hops,
    )


def _enforce_rate_limit(request: Request, session_id: str | None) -> None:
    """Raise 429 with ``Retry-After`` when a bucket is empty."""
    settings = getattr(request.app.state, "settings", None)
    limiter: RateLimiter | None = getattr(request.app.state, "rate_limiter", None)
    if limiter is None or (settings is not None and not settings.rate_limit_enabled):
        return

    decision = limiter.check(session_id, _client_ip(request))
    if decision.allowed:
        return

    telemetry: Telemetry | None = getattr(request.app.state, "telemetry", None)
    if telemetry is not None:
        telemetry.record_rate_limited(decision.scope)

    wait = decision.retry_after_seconds
    logger.info(
        "rate limited: scope=%s retry_after=%ss session=%s",
        decision.scope,
        wait,
        session_id or "-",
    )
    raise HTTPException(
        status_code=status.HTTP_429_TOO_MANY_REQUESTS,
        detail={
            "message": RATE_LIMITED_MESSAGE,
            "retry_after_seconds": wait,
            "scope": decision.scope,
        },
        headers={"Retry-After": str(wait)},
    )


# --------------------------------------------------------------------------- #
# Routes
# --------------------------------------------------------------------------- #
@router.post("/chat", response_model=BetaChatResponse)
async def beta_chat(
    payload: BetaChatRequest, orchestrator: OrchestratorDep, request: Request
) -> BetaChatResponse:
    """Run one turn and return it in the beta UI's envelope.

    ``blocked`` is true exactly when the **input** safety gate short-circuited,
    which is what :attr:`GuidanceResult.crisis` records: that path returns
    before retrieval and generation run.
    """
    _enforce_rate_limit(request, payload.session_id)
    await _require_consent(request, orchestrator, payload.session_id)

    turn = UserTurn(message=payload.message, session_id=payload.session_id)
    try:
        result = await orchestrator.handle_turn(turn)
    except Exception as exc:
        logger.exception("pipeline failure on beta /api/chat")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="the guidance pipeline failed; please try again",
        ) from exc

    telemetry: Telemetry | None = getattr(request.app.state, "telemetry", None)
    if telemetry is not None:
        telemetry.record_turn(result, surface="beta")

    generation = result.generation
    return BetaChatResponse(
        message_id=result.message_id,
        reply=result.answer,
        blocked=result.crisis,
        emotion=BetaEmotion(
            label=result.emotion.dominant, score=result.emotion.dominant_score
        ),
        intent=BetaIntent(
            label=result.intent.intent.value,
            crisis_score=result.intent.semantic_crisis_score,
        ),
        citations=_citations_for(result),
        memory=BetaMemory(
            turn_count=result.memory.turn_count,
            summary_included=result.memory.summary_included,
            recent_turns_injected=result.memory.recent_turns_injected,
        ),
        meta=BetaMeta(
            provider=generation.provider if generation else None,
            model=(generation.model or None) if generation else None,
            latency_ms=result.total_latency_ms,
            stage_latency_ms=dict(result.timings),
        ),
    )


@router.post("/consent", response_model=BetaConsentResponse)
async def beta_consent(
    payload: BetaConsentRequest, orchestrator: OrchestratorDep, request: Request
) -> BetaConsentResponse:
    """Record that a session accepted a specific version of the beta notice.

    Creating the session as a side effect is deliberate: consent is the first
    thing that happens, before any message exists to create one.
    """
    settings = getattr(request.app.state, "settings", None)
    required = settings.consent_version if settings is not None else "v1"
    if payload.version != required:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": CONSENT_REQUIRED_CODE,
                "message": "That consent notice is out of date; please reload.",
                "required_version": required,
            },
        )

    record = await orchestrator.repository.record_consent(payload.session_id, payload.version)
    logger.info("consent recorded: session=%s version=%s", record.id, payload.version)
    return BetaConsentResponse(
        session_id=record.id,
        consent_version=record.consent_version or payload.version,
        consent_at=record.consent_at or datetime.now(UTC),
    )


@router.post("/feedback", response_model=BetaFeedbackResponse)
async def beta_feedback(
    payload: BetaFeedbackRequest, orchestrator: OrchestratorDep
) -> BetaFeedbackResponse:
    """Record a tester's verdict on one assistant turn.

    The message must exist and must be an assistant turn: feedback on a
    user's own message, or on an id that was never served, is a bug in the
    caller and is rejected rather than stored as noise.

    Not rate limited. It costs one small write, no model call, and a tester
    whose vote is refused simply stops voting - which loses the signal the beta
    exists to collect.
    """
    record = await orchestrator.repository.get_message(payload.message_id)
    if record is None or record.role != "assistant":
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="no assistant turn with that id",
        )

    stored = await orchestrator.repository.upsert_feedback(
        FeedbackRecord(
            id="",
            message_id=payload.message_id,
            session_id=record.session_id,
            rating=payload.rating,
            comment=payload.comment.strip(),
        )
    )
    logger.info(
        "feedback: message=%s rating=%s comment_chars=%d",
        stored.message_id,
        stored.rating,
        len(stored.comment),
    )
    return BetaFeedbackResponse(
        message_id=stored.message_id, rating=stored.rating, comment=stored.comment
    )


@router.get("/sessions/{session_id}/messages", response_model=BetaMessagesResponse)
async def beta_session_messages(
    session_id: str,
    orchestrator: OrchestratorDep,
    limit: Annotated[int, Query(ge=1, le=200)] = 50,
) -> BetaMessagesResponse:
    """Persisted turns for one session, oldest first, for reload continuity."""
    records = await orchestrator.repository.list_messages(session_id, limit=limit)
    return BetaMessagesResponse(
        session_id=session_id,
        messages=[
            BetaMessage(
                id=record.id,
                role=record.role,
                content=record.content,
                blocked=record.crisis,
                created_at=record.created_at,
            )
            for record in records
        ],
    )
